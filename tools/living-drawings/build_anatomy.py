#!/usr/bin/env python3
"""Pack the R04 reference STL instances into anatomy-mesh.js for anatomy.html.

The R04 build script exports every assembly instance in body coordinates (mm):
X rearward, Y outward from the near wall, Z up, origin at the lower body pivot.
Moving leg parts are exported at the 30 degree neutral pose.
This script keeps those coordinates. It quantizes positions to 0.02 mm and
merges duplicate vertices. It does not change geometry.

Usage: python3 build_anatomy.py [--check]
"""
from pathlib import Path
import base64, hashlib, json, struct, sys
import numpy as np

HERE = Path(__file__).resolve().parent
R04 = HERE.parent.parent / 'cad' / 'prints' / 'one-leg-body-r04'
OUT = HERE / 'anatomy-mesh.js'
Q = 0.02  # mm per quantization step

SKIP = ('fixture_', '_component_space', 'pico_USB_access', 'wheel')


def role(name):
    if name in ('lower_link',):
        return 'lower_link'
    if name in ('upper_link',):
        return 'upper_link'
    if name in ('carrier', 'carrier_lower_spacer', 'carrier_upper_spacer', 'gearbox', 'motor',
                'encoder', 'motor_pilot', 'shaft', 'hub'):
        return 'carrier'
    if name.endswith('_PCB') or name.startswith('pico_header') or name.endswith('_insulating_board') \
            or name.startswith('ST3215_'):
        return 'electronics'
    return 'housing'


def read_stl(path):
    data = path.read_bytes()
    n = struct.unpack_from('<I', data, 80)[0]
    if 84 + 50 * n != len(data):
        raise SystemExit(f'{path.name}: not a binary STL')
    rec = np.frombuffer(data, dtype=np.dtype([('n', '<f4', 3), ('v', '<f4', (3, 3)), ('a', '<u2')]),
                        count=n, offset=84)
    return rec['v'].reshape(-1, 3).astype(np.float64)


def pack(path):
    verts = read_stl(path)
    q = np.round(verts / Q).astype(np.int64)
    if np.abs(q).max() >= 32767:
        raise SystemExit(f'{path.name}: outside the int16 range')
    uniq, inv = np.unique(q, axis=0, return_inverse=True)
    tris = inv.reshape(-1, 3)
    keep = (tris[:, 0] != tris[:, 1]) & (tris[:, 1] != tris[:, 2]) & (tris[:, 0] != tris[:, 2])
    tris = tris[keep]
    idx_t = '<u2' if len(uniq) < 65536 else '<u4'
    return {
        'p': base64.b64encode(uniq.astype('<i2').tobytes()).decode(),
        'i': base64.b64encode(tris.astype(idx_t).tobytes()).decode(),
        'w': 2 if idx_t == '<u2' else 4,
        't': int(len(tris)),
    }


def build():
    manifest = json.loads((R04 / 'manifest.json').read_text())
    parts = []
    for inst in manifest['assembly']:
        name = inst['name']
        if any(s in name for s in SKIP):
            continue
        f = R04 / inst['file']
        item = {'n': name, 'r': role(name), 'part': inst.get('part_id'), 'ref': bool(inst.get('reference_only'))}
        item.update(pack(f))
        parts.append(item)
    src = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()[:16]
           for p in [R04 / 'manifest.json', R04 / 'parameters.json']}
    body = {'revision': manifest['revision'], 'date': manifest['date'], 'units': 'mm', 'quantum_mm': Q,
            'frame': 'X rearward, Y outward from near wall, Z up, origin at lower body pivot',
            'neutral_deg': 30, 'source': src, 'parts': parts}
    text = ('/* Generated by build_anatomy.py from cad/prints/one-leg-body-r04/reference. Do not edit. */\n'
            'window.HuxAnatomyMesh = ' + json.dumps(body, separators=(',', ':')) + ';\n')
    return text, parts


if __name__ == '__main__':
    text, parts = build()
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print('anatomy-mesh.js is current' if ok else 'anatomy-mesh.js is stale: run python3 build_anatomy.py')
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print(f'{len(parts)} parts, {sum(p["t"] for p in parts)} triangles, {len(text)/1e6:.2f} MB -> {OUT.name}')
